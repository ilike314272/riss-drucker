"""Structure search over effective-Hamiltonian terms (README 7, M7 baseline).

The proposer emits grammar terms; physics verifies them. Pieces:

* Proposer protocol: propose(context) -> list of term strings.
  - EnumerativeProposer: all totally symmetric, Hermitian, polyad-conserving
    terms up to a ladder order, generated by symmetrizing every seed monomial
    and deduplicated by canonical form (the "dictionary" of README 7).
  - CallableProposer: wraps any callable (e.g. a language model run offline)
    that maps a JSON diagnostics context to term strings; its output goes
    through the same parser and compile certificates, so a malformed or
    non-symmetric proposal is rejected, never fitted.
* relevance(): sparse Bayesian (ARD / relevance-vector) ranking of candidate
  terms from Hellmann-Feynman design columns at the current fit (whitened).
  Caveat (found in testing): an off-diagonal resonance operator added with
  zero coefficient has zero Hellmann-Feynman derivative (it shifts levels only
  at second order), so linearized relevance cannot see resonances. search()
  therefore scores candidates by trial fits and evidence; ARD is a cheap
  pre-ranking for diagonal-type terms only.
* laplace_log_evidence(): model evidence of a fitted structure (Gaussian prior
  per parameter, Laplace approximation) for accepting/rejecting additions.
* search(): greedy forward selection; a candidate is accepted only if it is
  identifiable (full rank, no new null direction) and raises the evidence.
"""
from __future__ import annotations

import itertools
import json
import math
from dataclasses import dataclass, field
from typing import Callable, Protocol, Sequence

import numpy as np

from .fit import fit as _fit
from .grammar import GrammarError, canonical, normal_order, poly_add, dagger
from .solve import solve
from .vib import COMPONENTS, Symmetrizer, VibSpec, _polyad_change, compile_vib


class Proposer(Protocol):
    def propose(self, context: dict) -> list[str]: ...


def _sym_str(word) -> str:
    return " ".join(f"a{m}{c}{'+' if k == 'c' else ''}" for k, m, c in word)


@dataclass
class EnumerativeProposer:
    orders: tuple = (2, 3, 4)
    prefix: str = "c"

    def propose(self, context: dict) -> list[str]:
        spec: VibSpec = context["spec"]
        sym = Symmetrizer(spec)
        osc = [(m.name, c) for m in spec.modes for c in COMPONENTS[m.dim]]
        existing = {canonical(t) for t in context.get("existing_polys", [])}
        seen, out = set(existing), []
        for order in self.orders:
            for n_cr in range(order + 1):
                for cr in itertools.combinations_with_replacement(osc, n_cr):
                    for an in itertools.combinations_with_replacement(osc, order - n_cr):
                        word = tuple(("c", m, c) for m, c in cr) + tuple(("a", m, c) for m, c in an)
                        if _polyad_change(spec, word) != 0:
                            continue
                        if n_cr < order - n_cr:  # its Hermitian conjugate is enumerated too
                            continue
                        p = sym({word: 1.0})
                        p = normal_order(poly_add(p, dagger(p)))
                        if not p:
                            continue
                        key = canonical(p)
                        if key in seen:
                            continue
                        seen.add(key)
                        # Always Hermitize: a balanced seed is not necessarily self-adjoint.
                        out.append(f"{self.prefix}{order}_{len(out)}: sym({_sym_str(word)}) + h.c.")
        return out


@dataclass
class CallableProposer:
    """Wrap an external proposer (e.g. a language model, run offline) behind the grammar."""
    fn: Callable[[str], str]

    def propose(self, context: dict) -> list[str]:
        payload = json.dumps({k: v for k, v in context.items() if k in ("diagnostics", "existing_terms", "modes",
                                                                       "group", "grammar")}, default=str)
        reply = self.fn(payload)
        return [ln.strip() for ln in reply.splitlines() if ":" in ln and not ln.strip().startswith("#")]


def relevance(design: np.ndarray, residual: np.ndarray, *, max_iter: int = 500, prune: float = 1e10) -> np.ndarray:
    """Tipping-style ARD on whitened residuals: returns relevance |mu_k| / sd_k
    (0 for pruned columns). design columns are dE/dt_k / sigma."""
    X = design / np.maximum(np.linalg.norm(design, axis=0), 1e-300)
    n, k = X.shape
    alpha = np.ones(k)
    active = np.ones(k, bool)
    mu = np.zeros(k)
    Sigma = np.eye(k)
    for _ in range(max_iter):
        A = X[:, active]
        S = np.linalg.pinv(A.T @ A + np.diag(alpha[active]))
        m = S @ A.T @ residual
        gamma = 1 - alpha[active] * np.diag(S)
        new = gamma / np.maximum(m**2, 1e-300)
        prev = alpha.copy()
        alpha[active] = new
        mu[:] = 0
        mu[active] = m
        Sigma = S
        active = alpha < prune
        if not active.any():
            break
        if np.max(np.abs(np.log(alpha[active] + 1e-300) - np.log(prev[active] + 1e-300))) < 1e-6:
            break
    rel = np.zeros(k)
    if active.any():
        A = X[:, active]
        S = np.linalg.pinv(A.T @ A + np.diag(alpha[active]))
        m = S @ A.T @ residual
        rel[active] = np.abs(m) / np.sqrt(np.diag(S))
    return rel


def laplace_log_evidence(fitres, prior_sigma: dict | float = 1e3) -> float:
    """log p(data | structure) with independent N(0, s_k^2) priors (Laplace)."""
    names = fitres.free
    s = np.array([prior_sigma.get(n, 1e3) if isinstance(prior_sigma, dict) else prior_sigma for n in names])
    th = np.array([fitres.theta[n] for n in names])
    idx = [fitres.param_names.index(n) for n in names]
    cov = np.asarray(fitres.covariance)[np.ix_(idx, idx)]
    # precision of the likelihood around theta_hat = pinv(cov); add prior precision
    H = np.linalg.pinv(cov) + np.diag(1 / s**2)
    sign, logdetH = np.linalg.slogdet(H)
    return float(-0.5 * fitres.chi2 - 0.5 * np.sum((th / s) ** 2) - np.sum(np.log(s)) - 0.5 * logdetH)


@dataclass
class SearchStep:
    term: str
    accepted: bool
    delta_log_evidence: float
    chi2_before: float
    chi2_after: float
    reason: str


@dataclass
class SearchResult:
    spec: VibSpec
    fit: object
    steps: list = field(default_factory=list)
    ranking: list = field(default_factory=list)


def _design(model, fitres, observations) -> tuple[np.ndarray, np.ndarray]:
    keys = [b["key"] for b in model.blocks]
    need = max(o.index for o in observations) + 1
    sol = solve(model, fitres.theta, nlowest=need, keep_vectors=True, method="dense")
    jac = {}
    rows, r = [], []
    for o in observations:
        bi = keys.index(o.block)
        if bi not in jac:
            jac[bi] = model.jacobian(bi, np.asarray(sol.results[bi]["eigenvectors"]))
        rows.append(jac[bi][o.index] / o.sigma)
        r.append((o.energy - sol.results[bi]["eigenvalues"][o.index]) / o.sigma)
    return np.array(rows), np.array(r)


def search(spec: VibSpec, observations_for: Callable, theta0: dict, candidates: Sequence[str], *,
           max_add: int = 5, prior_sigma: float = 1e3, top: int = 10, start_value: float = 1.0) -> SearchResult:
    """Greedy evidence-based forward selection with trial fits.

    observations_for(model) -> observations labelled for that model. Each round
    fits every remaining candidate added to the current structure (started at
    start_value, since resonances are invisible at exactly 0), scores it by the
    Laplace log evidence, and accepts the best if it is identifiable (no null
    direction) and raises the evidence.
    """
    cur = VibSpec(spec.modes, spec.group, list(spec.polyads), list(spec.terms), spec.max_order)
    model = compile_vib(cur)
    obs = observations_for(model)
    f = _fit(model, obs, {n: theta0.get(n, 0.0) for n in model.param_names})
    logZ = laplace_log_evidence(f, prior_sigma)
    steps, remaining, ranking = [], list(candidates), []
    for _ in range(max_add):
        scored = []
        for c in remaining:
            try:
                trial = VibSpec(cur.modes, cur.group, cur.polyads, cur.terms + [c], cur.max_order)
                tm = compile_vib(trial)
            except GrammarError:
                continue
            new = [n for n in tm.param_names if n not in f.theta]
            tobs = observations_for(tm)
            tf = _fit(tm, tobs, {n: f.theta.get(n, start_value if n in new else 0.0) for n in tm.param_names})
            scored.append((laplace_log_evidence(tf, prior_sigma), c, trial, tm, tobs, tf))
        if not scored:
            break
        scored.sort(key=lambda x: -x[0])
        ranking = [(c, z - logZ) for z, c, *_ in scored[:top]]
        z, best, trial, tm, tobs, tf = scored[0]
        ident = not tf.null_directions
        acc = ident and z > logZ
        steps.append(SearchStep(best, acc, z - logZ, f.chi2, tf.chi2,
                                "accepted" if acc else ("not identifiable" if not ident else "evidence decreased")))
        remaining.remove(best)
        if not acc:
            break
        cur, model, obs, f, logZ = trial, tm, tobs, tf, z
    return SearchResult(cur, f, steps, ranking)
